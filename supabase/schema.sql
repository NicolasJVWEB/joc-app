-- Une ligne = une personne (avec ou sans compte)
create table if not exists public.participants (
  id uuid primary key default gen_random_uuid(),
  compte_id uuid unique references auth.users (id) on delete set null,
  prenom text not null check (char_length(prenom) between 1 and 40),
  nom text check (char_length(nom) <= 60),
  surnom text check (char_length(surnom) <= 40),
  age int check (age between 1 and 120),
  avatar text not null default '🙂' check (char_length(avatar) <= 16),
  photo text,
  devise text check (char_length(devise) <= 140),
  equipe_id text references public.equipes (id) on delete set null,
  present boolean not null default false,
  est_admin boolean not null default false,
  cree_le timestamptz not null default now()
);

create table if not exists public.epreuves (
  id bigint generated by default as identity primary key,
  ordre int not null default 0,
  nom text not null,
  emoji text not null default '🏁',
  horaire text not null default '',
  lieu text not null default '',
  description text not null default '',
  statut text not null default 'a_venir' check (statut in ('a_venir', 'en_cours', 'terminee'))
);

create table if not exists public.scores (
  epreuve_id bigint not null references public.epreuves (id) on delete cascade,
  equipe_id text not null references public.equipes (id) on delete cascade,
  rang int check (rang >= 1),
  points numeric,
  primary key (epreuve_id, equipe_id)
);

create table if not exists public.palmares (
  id bigint generated by default as identity primary key,
  participant_id uuid not null references public.participants (id) on delete cascade,
  annee int not null,
  titre text not null check (char_length(titre) <= 120)
);

-- ---------- Fonctions utilitaires ----------

create or replace function public.est_inscrit() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from participants where compte_id = auth.uid());
$$;

create or replace function public.est_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from participants where compte_id = auth.uid() and est_admin);
$$;

-- Un participant ne peut pas se nommer admin, changer d'équipe ou de compte tout seul
create or replace function public.proteger_participant() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  -- 'joc.systeme' est posé uniquement par la fonction rejoindre() ci-dessous
  if not public.est_admin() and coalesce(current_setting('joc.systeme', true), '') <> 'oui' then
    new.est_admin := old.est_admin;
    new.equipe_id := old.equipe_id;
    new.compte_id := old.compte_id;
  end if;
  return new;
end $$;

drop trigger if exists proteger_participant on public.participants;
create trigger proteger_participant before update on public.participants
  for each row execute function public.proteger_participant();

-- Liste des prénoms pas encore reliés à un compte (seulement avec le bon code)
create or replace function public.liste_a_rejoindre(p_code text)
returns table (id uuid, prenom text, surnom text, equipe_id text)
language plpgsql stable security definer set search_path = public as $$
begin
  if not exists (select 1 from reglages where p_code in (code_acces, code_admin)) then
    raise exception 'Code d''accès incorrect';
  end if;
  return query
    select p.id, p.prenom, p.surnom, p.equipe_id from participants p
    where p.compte_id is null order by p.prenom;
end $$;

-- Relie le compte connecté à un participant (existant ou nouveau)
create or replace function public.rejoindre(p_code text, p_participant uuid default null, p_prenom text default null)
returns uuid
language plpgsql security definer set search_path = public as $$
declare
  v_admin boolean;
  v_id uuid;
begin
  if auth.uid() is null then raise exception 'Connexion requise'; end if;

  select (p_code = code_admin) into v_admin from reglages where p_code in (code_acces, code_admin);
  if v_admin is null then raise exception 'Code d''accès incorrect'; end if;
  perform set_config('joc.systeme', 'oui', true);

  select id into v_id from participants where compte_id = auth.uid();
  if v_id is null then
    if p_participant is not null then
      update participants set compte_id = auth.uid() where id = p_participant and compte_id is null
        returning id into v_id;
      if v_id is null then raise exception 'Ce prénom est déjà relié à un compte'; end if;
    else
      if coalesce(trim(p_prenom), '') = '' then raise exception 'Prénom obligatoire'; end if;
      insert into participants (compte_id, prenom) values (auth.uid(), trim(p_prenom)) returning id into v_id;
    end if;
  end if;

  if v_admin then update participants set est_admin = true where id = v_id; end if;
  perform set_config('joc.systeme', '', true);
  return v_id;
end $$;

revoke execute on function public.liste_a_rejoindre(text) from public, anon;
revoke execute on function public.rejoindre(text, uuid, text) from public, anon;
grant execute on function public.liste_a_rejoindre(text) to authenticated;
grant execute on function public.rejoindre(text, uuid, text) to authenticated;

-- ---------- Sécurité : qui peut lire et écrire quoi ----------
-- Lecture : uniquement les personnes connectées ET inscrites avec le code.
-- Écriture : les organisateurs (admins). Chacun peut modifier sa propre fiche.

alter table public.reglages enable row level security;
alter table public.infos enable row level security;
alter table public.equipes enable row level security;
alter table public.participants enable row level security;
alter table public.epreuves enable row level security;
alter table public.scores enable row level security;
alter table public.palmares enable row level security;

do $$
declare t text;
begin
  foreach t in array array['infos', 'equipes', 'epreuves', 'scores', 'palmares'] loop
    execute format('drop policy if exists lecture on public.%I', t);
    execute format('create policy lecture on public.%I for select to authenticated using (public.est_inscrit())', t);
    execute format('drop policy if exists ecriture_admin on public.%I', t);
    execute format('create policy ecriture_admin on public.%I for all to authenticated using (public.est_admin()) with check (public.est_admin())', t);
  end loop;
end $$;

drop policy if exists lecture on public.participants;
create policy lecture on public.participants for select to authenticated using (public.est_inscrit());
drop policy if exists modif on public.participants;
create policy modif on public.participants for update to authenticated
  using (compte_id = auth.uid() or public.est_admin())
  with check (compte_id = auth.uid() or public.est_admin());
drop policy if exists ajout_admin on public.participants;
create policy ajout_admin on public.participants for insert to authenticated with check (public.est_admin());
drop policy if exists suppr_admin on public.participants;
create policy suppr_admin on public.participants for delete to authenticated using (public.est_admin());

